/**
 * Single configuration constant for Koban-to-PKR conversion (10 Kobans = PKR 1).
 */
export const KOBAN_TO_PKR_RATE = 10;

export function kobansToPkr(kobans: number): number {
  return Math.round((Math.max(0, kobans) / KOBAN_TO_PKR_RATE) * 100) / 100;
}

