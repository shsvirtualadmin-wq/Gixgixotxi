export const MATRIX_AVATAR_KEYS = MATRIX_AVATARS.map((a) => a.key);

export function isValidAvatar(key?: string | null, variant?: string | null): boolean {
  if (!key || typeof key !== 'string') return false;
  const keyExists = MATRIX_AVATARS.some((a) => a.key === key);
  if (!keyExists) return false;
  if (variant && !MATRIX_VARIANTS[variant as MatrixAvatarVariant]) return false;
  return true;
}

/**
 * Deterministic default avatar selector based on user id or string seed.
 * Ensures the avatar is stable per user, never random per load.
 */
export function getDefaultAvatar(seed?: string | null): { key: string; variant: MatrixAvatarVariant } {
  if (!seed || typeof seed !== 'string') {
    return { key: 'skull-01', variant: 'red-on-black' };
  }
  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
    hash |= 0;
  }
  const abs = Math.abs(hash);
  const selectedKey = MATRIX_AVATARS[abs % MATRIX_AVATARS.length].key;
  const variants: MatrixAvatarVariant[] = ['red-on-black', 'white-on-black', 'black-on-red', 'white-on-red'];
  const selectedVariant = variants[(abs >> 3) % variants.length];
  return { key: selectedKey, variant: selectedVariant };
}
